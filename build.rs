//! Build-time application icon wiring.
//!
//! One artwork source serves every surface that shows the app icon:
//!
//! - `ui/favicon.ico` is compiled into the Windows executable as the
//!   `IDI_ICON1` resource, so Explorer, the taskbar and any shortcut the
//!   user creates from the binary show it. The same file is served at
//!   `/favicon.ico` by the embedded UI handler.
//! - `ui/img/td3-control.png` is decoded to raw RGBA and written to
//!   `OUT_DIR` for the launcher window icon, which needs pixels rather
//!   than an encoded file. Decoding here keeps the PNG the only copy of
//!   the artwork, so the window icon can never drift from the tab icon.
//!
//! The Windows resource step is best effort: a host without a resource
//! compiler emits a cargo warning and produces a binary without an icon
//! resource rather than failing the build.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const ICO_PATH: &str = "ui/favicon.ico";
const PNG_PATH: &str = "ui/img/td3-control.png";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", ICO_PATH);
    println!("cargo:rerun-if-changed={}", PNG_PATH);

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    write_launcher_icon(&out_dir);

    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        embed_windows_icon();
    }
}

/// Decode the PNG and write `launcher_icon.rgba` plus a `launcher_icon.rs`
/// that exposes its bytes and dimensions. Any failure here means the
/// committed artwork is missing or unreadable, which is a build error.
fn write_launcher_icon(out_dir: &Path) {
    let file =
        fs::File::open(PNG_PATH).unwrap_or_else(|e| panic!("cannot open {}: {}", PNG_PATH, e));
    let decoder = png::Decoder::new(std::io::BufReader::new(file));
    let mut reader = decoder
        .read_info()
        .unwrap_or_else(|e| panic!("cannot read {} header: {}", PNG_PATH, e));

    let size = reader
        .output_buffer_size()
        .unwrap_or_else(|| panic!("{}: image too large to decode", PNG_PATH));
    let mut buf = vec![0; size];
    let info = reader
        .next_frame(&mut buf)
        .unwrap_or_else(|e| panic!("cannot decode {}: {}", PNG_PATH, e));
    buf.truncate(info.buffer_size());

    let rgba = match info.color_type {
        png::ColorType::Rgba => buf,
        png::ColorType::Rgb => buf
            .as_chunks::<3>()
            .0
            .iter()
            .flat_map(|p| [p[0], p[1], p[2], 0xff])
            .collect(),
        other => panic!(
            "{} must be RGB or RGBA, found {:?}; re-export the artwork",
            PNG_PATH, other
        ),
    };
    let expected = info.width as usize * info.height as usize * 4;
    assert_eq!(
        rgba.len(),
        expected,
        "{}: decoded {} bytes for {}x{}, expected {}",
        PNG_PATH,
        rgba.len(),
        info.width,
        info.height,
        expected
    );

    let rgba_path = out_dir.join("launcher_icon.rgba");
    fs::write(&rgba_path, &rgba)
        .unwrap_or_else(|e| panic!("cannot write {}: {}", rgba_path.display(), e));

    let source = format!(
        "// Generated by build.rs from {}. Do not edit.\n\
         pub const WIDTH: u32 = {};\n\
         pub const HEIGHT: u32 = {};\n\
         pub const RGBA: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/launcher_icon.rgba\"));\n",
        PNG_PATH, info.width, info.height
    );
    let rs_path = out_dir.join("launcher_icon.rs");
    fs::write(&rs_path, source)
        .unwrap_or_else(|e| panic!("cannot write {}: {}", rs_path.display(), e));
}

/// Compile `ui/favicon.ico` into the executable's resource table.
///
/// Requires a resource compiler (`rc.exe` from the Windows SDK on MSVC
/// hosts, `windres` or `llvm-rc` when cross-compiling). Without one the
/// build continues and the binary carries the default Cargo icon.
fn embed_windows_icon() {
    let mut resource = winresource::WindowsResource::new();
    resource.set_icon(ICO_PATH);
    if let Err(e) = resource.compile() {
        println!(
            "cargo:warning=executable icon not embedded ({}): no resource compiler available",
            e
        );
    }
}
